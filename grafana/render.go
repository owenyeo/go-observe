// A regex end anchor ($) is valid PromQL; only Grafana variable syntax is forbidden.
var dashboardVariable = regexp.MustCompile(`\$(?:\{|[A-Za-z_])`)

// Definition belongs in the consuming repository as Go source. Version identifies
// a monitoring release separately from the application's binary version.
// Definitions and targets must remain immutable while Render runs.
type Definition struct {
	Service string
	Version string
	// OverviewUID selects the generated SLO overview's UID. Without objectives,
	// it only links alerts; it does not add that dashboard to the bundle.
	// When empty, alerts link to the first dashboard in the bundle, if any.
	OverviewUID      string
	Objectives       []slo.Objective
	Guardrails       []Guardrail
	CustomDashboards []json.RawMessage // classic JSON or dashboard.grafana.app/v2 resources.
	ReplicaLabel     string
}

// Target binds one release to an environment. Scope is required and is enforced
// on generated SLO queries; arbitrary guardrail queries must use ${scope}.
// FolderUID and datasource UIDs must already exist. The SDK never creates global routes.
// Namespace selects the native dashboard API namespace (for example default on
// local Grafana or stacks-<id> in Cloud); it does not change metric query scope.
type Target struct {
	Environment   string            `json:"environment"`
	URL           string            `json:"url"`
	FolderUID     string            `json:"folderUID"`
	PrometheusUID string            `json:"prometheusUID"`
	LokiUID       string            `json:"lokiUID,omitempty"`
	Scope         map[string]string `json:"scope"`
	ContactPoint  string            `json:"contactPoint,omitempty"`
	EnableAlerts  bool              `json:"enableAlerts"`
	Namespace     string            `json:"namespace,omitempty"` // native dashboard API namespace; otherwise use the resource's namespace.
}

// Guardrail is an operational threshold, separate from an SLO's error budget.
type Guardrail struct {
	ID          string
	Name        string
	Description string
	Query       string // PromQL or LogQL with ${scope} inside a selector.
	Source      string // prometheus or loki.
	Operator    string // gt or lt.
	Threshold   float64
	Pending     time.Duration
	Severity    string
	Response    slo.Response
}

// Bundle contains no credentials and is the artifact reviewed/promoted by CI.
type Bundle struct {
	SchemaVersion int               `json:"schemaVersion"`
	Service       string            `json:"service"`
	Version       string            `json:"version"`
	Target        Target            `json:"target"`
	Dashboards    []json.RawMessage `json:"dashboards"`
	Alerts        []Rule            `json:"alerts"`
}

// Rule is an alert provisioning document generated by Render.
type Rule struct {
	UID                  string            `json:"uid"`
	Title                string            `json:"title"`
	FolderUID            string            `json:"folderUID"`
	RuleGroup            string            `json:"ruleGroup"`
	Condition            string            `json:"condition"`
	For                  string            `json:"for"`
	NoDataState          string            `json:"noDataState"`
	ExecErrState         string            `json:"execErrState"`
	IsPaused             bool              `json:"isPaused"`
	Annotations          map[string]string `json:"annotations"`
	Labels               map[string]string `json:"labels"`
	Data                 []Query           `json:"data"`
	NotificationSettings map[string]string `json:"notification_settings,omitempty"`
}

// Query is one Grafana alert data-source or expression query.
type Query struct {
	RefID             string           `json:"refId"`
	DatasourceUID     string           `json:"datasourceUid"`
	RelativeTimeRange map[string]int64 `json:"relativeTimeRange"`
	Model             map[string]any   `json:"model"`
	QueryType         string           `json:"queryType,omitempty"`
}

var releaseVersion = regexp.MustCompile(`^(0|[1-9][0-9]*)\.(0|[1-9][0-9]*)\.(0|[1-9][0-9]*)$`)
var resourceID = regexp.MustCompile(`^[a-zA-Z0-9_-]{1,40}$`)

// ResourceUID derives a stable identifier without embedding deployment names.
func ResourceUID(service, environment, kind, id string) string {
	hash := sha256.Sum256([]byte(service + "\x00" + environment + "\x00" + kind + "\x00" + id))
	return fmt.Sprintf("observe-%x", hash[:12])
}

func owner(service, environment string) string { return service + ":" + environment }

// Render is deterministic and offline. Its output is safe to commit for review;
// endpoint and credential configuration is supplied separately by CI.
func Render(def Definition, target Target) (Bundle, error) {
	bundle := Bundle{SchemaVersion: 1, Service: def.Service, Version: def.Version, Target: target,
		Dashboards: []json.RawMessage{}, Alerts: []Rule{}}
	if !slo.ValidID(def.Service) || !slo.ValidID(target.Environment) || !releaseVersion.MatchString(def.Version) {
		return Bundle{}, errors.New("service/environment need stable lowercase IDs; monitoring version needs MAJOR.MINOR.PATCH")
	}
	if !resourceID.MatchString(target.FolderUID) || !resourceID.MatchString(target.PrometheusUID) || len(target.Scope) == 0 {
		return Bundle{}, errors.New("target needs a folder, Prometheus datasource and explicit query scope")
	}
	if def.OverviewUID != "" && !resourceID.MatchString(def.OverviewUID) {
		return Bundle{}, errors.New("overview UID must contain 1–40 letters, digits, underscores or hyphens")
	}
	if target.EnableAlerts && target.ContactPoint == "" {
		return Bundle{}, errors.New("active alerts need an explicit contact point")
	}
	seen := map[string]bool{}
	for _, objective := range def.Objectives {
		if err := objective.Validate(); err != nil {
			return Bundle{}, fmt.Errorf("SLO %s: %w", objective.ID, err)
		}
		if seen[objective.ID] {
			return Bundle{}, errors.New("duplicate objective ID")
		}
		seen[objective.ID] = true
		for _, policy := range objective.Alerts() {
			expression, err := objective.BurnExpression(policy, target.Scope)
			if err != nil {
				return Bundle{}, err
			}
			rule := newRule(def.Service, target, objective.ID+"-"+policy.ID, objective.Name+" — "+policy.Name, "prometheus", expression, "gt", 0, policy.Pending, policy.Severity, objective.Response)
			rule.Annotations["slo_id"] = objective.ID
			rule.Annotations["description"] = fmt.Sprintf("%s Target %.4g%% over %s; both %s and %s windows exceed the budget-consumption threshold. Inspect error_fraction={{ $values.C.Value }} and eligible_events={{ $values.D.Value }}.", objective.Description, 100*objective.Target, objective.Window, policy.LongWindow, policy.ShortWindow)
			total, _, ratio, _ := objective.SLI.Queries(policy.ShortWindow, target.Scope)
			rule.Data = append(rule.Data, sourceQuery("C", "prometheus", target.PrometheusUID, "1 - "+ratio, int64(policy.LongWindow/time.Second)), sourceQuery("D", "prometheus", target.PrometheusUID, total, int64(policy.LongWindow/time.Second)))
			bundle.Alerts = append(bundle.Alerts, rule)
		}
	}
	seen = map[string]bool{}
	for _, guardrail := range def.Guardrails {
		if !slo.ValidID(guardrail.ID) || seen[guardrail.ID] || guardrail.Name == "" || guardrail.Severity == "" || !strings.Contains(guardrail.Query, "${scope}") {
			return Bundle{}, errors.New("guardrail needs a unique ID, name, severity and ${scope} in its query")
		}
		seen[guardrail.ID] = true
		if guardrail.Source != "prometheus" && guardrail.Source != "loki" {
			return Bundle{}, errors.New("guardrail source must be prometheus or loki")
		}
		if guardrail.Source == "loki" && !resourceID.MatchString(target.LokiUID) {
			return Bundle{}, errors.New("Loki guardrails need a Loki datasource UID")
		}
		if guardrail.Operator != "gt" && guardrail.Operator != "lt" {
			return Bundle{}, errors.New("guardrail operator must be gt or lt")
		}
		if math.IsNaN(guardrail.Threshold) || math.IsInf(guardrail.Threshold, 0) || guardrail.Pending < 0 || guardrail.Pending%time.Second != 0 {
			return Bundle{}, errors.New("invalid guardrail threshold/pending period")
		}
		if err := guardrail.Response.Validate(); err != nil {
			return Bundle{}, err
		}
		query, err := scopedQuery(guardrail.Query, target.Scope)
		if err != nil {
			return Bundle{}, err
		}
		rule := newRule(def.Service, target, "guardrail-"+guardrail.ID, guardrail.Name, guardrail.Source, query, guardrail.Operator, guardrail.Threshold, guardrail.Pending, guardrail.Severity, guardrail.Response)
		rule.Annotations["description"] = guardrail.Description + " Observed={{ $values.A.Value }}; threshold=" + fmt.Sprint(guardrail.Threshold) + "; assess customer impact before assigning incident priority."
		bundle.Alerts = append(bundle.Alerts, rule)
	}
	if len(def.Objectives) > 0 {
		dash, err := overview(def, target)
		if err != nil {
			return Bundle{}, err
		}
		bundle.Dashboards = append(bundle.Dashboards, dash)
	}
	for _, raw := range def.CustomDashboards {
		var content map[string]any
		if err := json.Unmarshal(raw, &content); err != nil {
			return Bundle{}, fmt.Errorf("custom dashboard: %w", err)
		}
		document, err := parseDashboard(content)
		if err != nil {
			return Bundle{}, err
		}
		if document.native {
			if target.Namespace != "" {
				document.metadata()["namespace"] = target.Namespace
			}
			// Deployment metadata comes from the reviewed target, not a saved export.
			content["metadata"] = map[string]any{"name": document.uid(), "namespace": document.metadata()["namespace"],
				"annotations": map[string]any{"grafana.app/folder": target.FolderUID}}
		}
		tags, _ := document.spec()["tags"].([]any)
		document.spec()["tags"] = append(tags, "go-observe:"+owner(def.Service, target.Environment))
		encoded, err := json.Marshal(content)
		if err != nil {
			return Bundle{}, err
		}
		bundle.Dashboards = append(bundle.Dashboards, encoded)
	}
	dashboardUID := def.OverviewUID
	if dashboardUID == "" && len(bundle.Dashboards) > 0 {
		var first map[string]any
		_ = json.Unmarshal(bundle.Dashboards[0], &first)
		document, _ := parseDashboard(first)
		dashboardUID = document.uid()
	}
	if dashboardUID != "" {
		for index := range bundle.Alerts {
			bundle.Alerts[index].Annotations["dashboard_url"] = strings.TrimSuffix(target.URL, "/") + "/d/" + dashboardUID
		}
	}
	if err := bundle.Validate(); err != nil {
		return Bundle{}, err
	}
	return bundle, nil
}

func scopedQuery(query string, scope map[string]string) (string, error) {
	selector, err := (slo.Selector{Metric: "scope", Labels: scope}).Expression(nil)
	if err != nil {
		return "", err
	}
	query = strings.ReplaceAll(query, "${scope}", strings.TrimSuffix(strings.TrimPrefix(selector, "scope{"), "}"))
	if dashboardVariable.MatchString(query) {
		return "", errors.New("alert queries cannot depend on dashboard variables")
	}
	return query, nil
}

func sourceQuery(id, source, uid, expression string, lookback int64) Query {
	query := Query{RefID: id, DatasourceUID: uid, RelativeTimeRange: map[string]int64{"from": lookback, "to": 0},
		Model: map[string]any{"refId": id, "expr": expression, "instant": true, "range": false, "intervalMs": 1000, "maxDataPoints": 43200, "datasource": map[string]string{"type": source, "uid": uid}}}
	if source == "loki" {
		query.QueryType = "instant"
		query.Model["queryType"] = "instant"
	}
	return query
}

func newRule(service string, target Target, id, name, source, expression, operator string, threshold float64, pending time.Duration, severity string, response slo.Response) Rule {
	uid := target.PrometheusUID
	if source == "loki" {
		uid = target.LokiUID
	}
	// Grafana evaluates the data-source result A through a threshold expression B.
	// Keep the expression model separate from routing and response metadata.
	condition := map[string]any{
		"type":      "query",
		"evaluator": map[string]any{"type": operator, "params": []float64{threshold}},
		"operator":  map[string]string{"type": "and"},
		"query":     map[string]any{"params": []string{"B"}},
		"reducer":   map[string]any{"type": "last", "params": []any{}},
	}
	thresholdQuery := Query{
		RefID: "B", DatasourceUID: "__expr__",
		RelativeTimeRange: map[string]int64{"from": 0, "to": 0},
		Model: map[string]any{
			"refId": "B", "type": "threshold", "expression": "A",
			"datasource": map[string]string{"uid": "__expr__", "type": "__expr__"},
			"conditions": []any{condition},
		},
	}
	rule := Rule{UID: ResourceUID(service, target.Environment, "alert", id), Title: service + " / " + target.Environment + " / " + name,
		FolderUID: target.FolderUID, RuleGroup: ResourceUID(service, target.Environment, "group", "alerts"), Condition: "B", For: fmt.Sprint(int64(pending/time.Second)) + "s",
		NoDataState: "NoData", ExecErrState: "Error", IsPaused: !target.EnableAlerts,
		Labels:      map[string]string{"service_name": service, "environment": target.Environment, "severity": severity, "alert_id": id, "go_observe_owner": owner(service, target.Environment), "team": response.Owner},
		Annotations: map[string]string{"summary": name, "first_check": response.FirstCheck, "runbook_url": response.RunbookURL, "owner": response.Owner, "escalation": response.Escalation},
		Data:        []Query{sourceQuery("A", source, uid, expression, 21600), thresholdQuery},
	}
	if target.ContactPoint != "" {
		rule.NotificationSettings = map[string]string{"receiver": target.ContactPoint}
	}
	return rule
}

func overview(def Definition, target Target) (json.RawMessage, error) {
	ds := common.DataSourceRef{Type: cog.ToPtr("prometheus"), Uid: cog.ToPtr(target.PrometheusUID)}
	uid := def.OverviewUID
	if uid == "" {
		uid = ResourceUID(def.Service, target.Environment, "dashboard", "overview")
	}
	builder := dashboard.NewDashboardBuilder(def.Service+" — "+target.Environment).
		Uid(uid).Tags([]string{"go-observe:" + owner(def.Service, target.Environment)}).
		Description("Service reliability. Unknown or no-traffic measurements remain No data. Monitoring release "+def.Version).
		Timezone("browser").Time("now-1h", "now").Refresh("30s")
	id := uint32(1)
	y := uint32(0)
	for _, objective := range def.Objectives {
		_, _, ratio, err := objective.SLI.Queries(objective.Window, target.Scope)
		if err != nil {
			return nil, err
		}
		builder.WithPanel(stat.NewPanelBuilder().Id(id).Title(objective.Name + " — success").Description(objective.Description + fmt.Sprintf(" Target %.4g%% over %s.", 100*objective.Target, objective.Window)).
			GridPos(dashboard.GridPos{X: 0, Y: y, W: 12, H: 4}).Datasource(ds).Unit("percentunit").NoValue("No data / no traffic").
			Thresholds(dashboard.NewThresholdsConfigBuilder().Mode(dashboard.ThresholdsModeAbsolute).Steps([]dashboard.Threshold{{Color: "red"}, {Color: "green", Value: cog.ToPtr(objective.Target)}})).
			WithTarget(prom.NewDataqueryBuilder().RefId("A").Expr(ratio).Instant()))
		builder.WithPanel(stat.NewPanelBuilder().Id(id + 1).Title(objective.Name + " — budget remaining").Description("Negative values mean the error budget has been exceeded.").
			GridPos(dashboard.GridPos{X: 12, Y: y, W: 12, H: 4}).Datasource(ds).Unit("percentunit").NoValue("No data / no traffic").
			Thresholds(dashboard.NewThresholdsConfigBuilder().Mode(dashboard.ThresholdsModeAbsolute).Steps([]dashboard.Threshold{{Color: "red"}, {Color: "orange", Value: cog.ToPtr(0.0)}, {Color: "green", Value: cog.ToPtr(.25)}})).
			WithTarget(prom.NewDataqueryBuilder().RefId("A").Expr(fmt.Sprintf("1 - ((1 - %s) / %.17g)", ratio, 1-objective.Target)).Instant()))
		id += 2
		y += 4
	}
	row := dashboard.NewRowBuilder("Diagnostics — traffic and errors").Id(id).GridPos(dashboard.GridPos{X: 0, Y: y, W: 24, H: 1})
	id++
	diagnosticScope := map[string]string{}
	for key, value := range target.Scope {
		diagnosticScope[key] = value
	}
	if def.ReplicaLabel != "" {
		if _, exists := target.Scope[def.ReplicaLabel]; exists {
			return nil, errors.New("replica label cannot also be fixed in target scope")
		}
		for _, objective := range def.Objectives {
			for _, selector := range []slo.Selector{objective.SLI.Total, objective.SLI.Good} {
				if _, exists := selector.Labels[def.ReplicaLabel]; exists {
					return nil, errors.New("replica label cannot also be fixed in an SLI selector")
				}
				if _, exists := selector.Regex[def.ReplicaLabel]; exists {
					return nil, errors.New("replica label cannot also be matched in an SLI selector")
				}
			}
		}
		series, err := def.Objectives[0].SLI.Total.Expression(target.Scope)
		if err != nil {
			return nil, err
		}
		// Validate a label using the same selector validator before using it in a variable query.
		if _, err := (slo.Selector{Metric: "scope", Labels: map[string]string{def.ReplicaLabel: ""}}).Expression(nil); err != nil {
			return nil, err
		}
		query := "label_values(" + series + ", " + def.ReplicaLabel + ")"
		builder.WithVariable(dashboard.NewQueryVariableBuilder("replica").Label("Replica (diagnostics)").Datasource(ds).
			Query(dashboard.StringOrMap{String: &query}).Multi(true).IncludeAll(true).AllValue(".*").AllowCustomValue(false).
			Refresh(dashboard.VariableRefreshOnDashboardLoad).Current(dashboard.VariableOption{Text: dashboard.StringOrArrayOfString{String: cog.ToPtr("All")}, Value: dashboard.StringOrArrayOfString{String: cog.ToPtr("$__all")}}))
	}
	for _, objective := range def.Objectives {
		diagnosticSLI := objective.SLI
		if def.ReplicaLabel != "" {
			// Add the matcher to structured selectors first. Rewriting every opening
			// brace would also corrupt route values such as /orders/{id}.
			diagnosticSLI.Total.Regex = maps.Clone(diagnosticSLI.Total.Regex)
			diagnosticSLI.Good.Regex = maps.Clone(diagnosticSLI.Good.Regex)
			if diagnosticSLI.Total.Regex == nil {
				diagnosticSLI.Total.Regex = map[string]string{}
			}
			if diagnosticSLI.Good.Regex == nil {
				diagnosticSLI.Good.Regex = map[string]string{}
			}
			diagnosticSLI.Total.Regex[def.ReplicaLabel] = ".*"
			diagnosticSLI.Good.Regex[def.ReplicaLabel] = ".*"
		}
		total, _, ratio, err := diagnosticSLI.Queries(5*time.Minute, diagnosticScope)
		if err != nil {
			return nil, err
		}
		if def.ReplicaLabel != "" {
			// The replica selector is only for drill-down panels. SLO totals and alerts
			// always use the full service population, regardless of UI selection.
			matcher := def.ReplicaLabel + `=~".*"`
			filter := def.ReplicaLabel + `=~"${replica:regex}"`
			total = strings.ReplaceAll(total, matcher, filter)
			ratio = strings.ReplaceAll(ratio, matcher, filter)
		}
		row.WithPanel(timeseries.NewPanelBuilder().Id(id).Title(objective.Name + " — eligible events/s").GridPos(dashboard.GridPos{X: 0, Y: y + 1, W: 12, H: 7}).Datasource(ds).Unit("ops").WithTarget(prom.NewDataqueryBuilder().RefId("A").Expr("(" + total + ") / 300").Range()))
		row.WithPanel(timeseries.NewPanelBuilder().Id(id + 1).Title(objective.Name + " — error fraction").GridPos(dashboard.GridPos{X: 12, Y: y + 1, W: 12, H: 7}).Datasource(ds).Unit("percentunit").NoValue("No data / no traffic").WithTarget(prom.NewDataqueryBuilder().RefId("A").Expr("1 - " + ratio).Range()))
		id += 2
		y += 7
	}
	builder.WithRow(row)
	dash, err := builder.Build()
	if err != nil {
		return nil, err
	}
	return json.Marshal(dash)
}

// Validate also runs on artifacts read from disk, before any network request.
func (b Bundle) Validate() error {
	if b.SchemaVersion != 1 || !slo.ValidID(b.Service) || !slo.ValidID(b.Target.Environment) || !releaseVersion.MatchString(b.Version) {
		return errors.New("invalid bundle identity/schema/version")
	}
	if !resourceID.MatchString(b.Target.FolderUID) || !resourceID.MatchString(b.Target.PrometheusUID) || len(b.Target.Scope) == 0 {
		return errors.New("invalid bundle target")
	}
	parsed, err := url.Parse(b.Target.URL)
	if err != nil || parsed.Host == "" || (parsed.Scheme != "http" && parsed.Scheme != "https") || parsed.User != nil || parsed.RawQuery != "" || parsed.Fragment != "" {
		return errors.New("bundle needs an absolute HTTP(S) Grafana URL without credentials")
	}
	if _, err := (slo.Selector{Metric: "scope", Labels: b.Target.Scope}).Expression(nil); err != nil {
		return err
	}
	if environment, exists := b.Target.Scope["environment"]; exists && environment != b.Target.Environment {
		return errors.New("target environment differs from environment scope label")
	}
	if service, exists := b.Target.Scope["service_name"]; exists && service != b.Service {
		return errors.New("service differs from service_name scope label")
	}
	if len(b.Dashboards)+len(b.Alerts) == 0 {
		return errors.New("empty monitoring bundle")
	}
	seen := map[string]bool{}
	for _, raw := range b.Dashboards {
		var dashboard map[string]any
		if err := json.Unmarshal(raw, &dashboard); err != nil {
			return err
		}
		document, err := parseDashboard(dashboard)
		if err != nil {
			return err
		}
		uid := document.uid()
		if !resourceID.MatchString(uid) || seen[uid] || !hasTag(document.spec(), "go-observe:"+owner(b.Service, b.Target.Environment)) {
			return errors.New("dashboard needs a unique UID and matching ownership tag")
		}
		if document.native && (!resourceID.MatchString(document.namespace()) || document.folder() != b.Target.FolderUID || (b.Target.Namespace != "" && document.namespace() != b.Target.Namespace)) {
			return errors.New("native dashboard namespace or folder differs from target")
		}
		seen[uid] = true
	}
	for _, rule := range b.Alerts {
		if !resourceID.MatchString(rule.UID) || seen[rule.UID] || rule.FolderUID != b.Target.FolderUID || rule.Labels["go_observe_owner"] != owner(b.Service, b.Target.Environment) || rule.Labels["environment"] != b.Target.Environment || rule.Labels["service_name"] != b.Service || rule.RuleGroup != ResourceUID(b.Service, b.Target.Environment, "group", "alerts") {
			return errors.New("alert identity, scope or ownership mismatch")
		}
		seen[rule.UID] = true
		if rule.NoDataState != "NoData" || rule.ExecErrState != "Error" {
			return errors.New("missing data and evaluation errors must remain visible")
		}
		if rule.IsPaused == b.Target.EnableAlerts {
			return errors.New("alert activation differs from bundle target")
		}
		if !rule.IsPaused && (b.Target.ContactPoint == "" || rule.NotificationSettings["receiver"] != b.Target.ContactPoint) {
			return errors.New("active alert needs the declared contact point")
		}
		for _, query := range rule.Data {
			if query.DatasourceUID != "__expr__" && query.DatasourceUID != b.Target.PrometheusUID && query.DatasourceUID != b.Target.LokiUID {
				return errors.New("query uses an undeclared datasource")
			}
			if expression, ok := query.Model["expr"].(string); ok && dashboardVariable.MatchString(expression) {
				return errors.New("alert queries cannot use dashboard variables")
			}
		}
	}
	return nil
}

func hasTag(content map[string]any, expected string) bool {
	tags, _ := content["tags"].([]any)
	for _, tag := range tags {
		if tag == expected {
			return true
		}
	}
	return false
}
